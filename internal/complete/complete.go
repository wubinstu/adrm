// Package complete embeds the bash/zsh/fish completion scripts. The scripts
// call the hidden "<binary> __complete" entry point, which queries the live
// database for dynamic candidates (trash ids, original names, enum values).
//
// There is one script per (shell, binary) pair on purpose: adrm completes
// file paths like /bin/rm, adrmm completes subcommands, so the two
// vocabularies never appear in the same completion list.
package complete

// Bash returns the bash completion script for the given binary
// ("adrm" or "adrmm").
func Bash(cmd string) string {
	fn := "_" + cmd + "_complete"
	if cmd == "adrm" {
		// rm-compatible face: complete the small option set, then fall back
		// to file names. Subcommands never appear here.
		return `# >>> adrm bash completion (generated by 'adrmm completions bash') >>>
` + fn + `() {
    local cur cand
    cur="${COMP_WORDS[COMP_CWORD]}"
    # the array must stay quoted: an empty current word is a real argument
    # (it tells __complete we are completing a fresh word, not a prefix).
    cand="$("${ADRM_ADRM_BIN:-adrm}" __complete bash "${COMP_WORDS[@]:1}" 2>/dev/null)"
    COMPREPLY=()
    if [ -n "$cand" ]; then
        COMPREPLY=( $(compgen -W "$cand" -- "$cur") )
    fi
    if [ ${#COMPREPLY[@]} -eq 0 ]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
    fi
    return 0
}
complete -o default -o filenames -F ` + fn + ` adrm
# <<< adrm bash completion <<<
`
	}
	// management face: subcommands, their options and trash ids only.
	return `# >>> adrmm bash completion (generated by 'adrmm completions bash') >>>
` + fn + `() {
    local cur cand nofiles=0
    cur="${COMP_WORDS[COMP_CWORD]}"
    cand="$("${ADRM_ADRM_BIN:-adrmm}" __complete bash "${COMP_WORDS[@]:1}" 2>/dev/null)"
    COMPREPLY=()
    case "$cand" in
        *__nofiles__*) nofiles=1; cand="${cand//__nofiles__/}" ;;
    esac
    if [ -n "$cand" ]; then
        COMPREPLY=( $(compgen -W "$cand" -- "$cur") )
    fi
    # file names are never mixed into adrmm completions
    [ "$nofiles" = 1 ] && return 0
    return 0
}
complete -o default -F ` + fn + ` adrmm
# <<< adrmm bash completion <<<
`
}

// Zsh returns the zsh completion script for the given binary.
func Zsh(cmd string) string {
	if cmd == "adrm" {
		// rm-compatible face: options plus plain file names.
		return `#compdef adrm
# >>> adrm zsh completion (generated by 'adrmm completions zsh') >>>
_adrm() {
  local -a args out
  args=(${words[1,$CURRENT]})
  out=("${(@f)$(${ADRM_ADRM_BIN:-adrm} __complete zsh "${args[@]}" 2>/dev/null)}")
  out=(${out:#__nofiles__})
  if (( ${#out} )); then
    _describe -t adrm 'option' out
    return 0
  fi
  _files
}
compdef _adrm adrm
# <<< adrm zsh completion <<<
`
	}
	// management face: subcommands, options, ids; never files.
	return `#compdef adrmm
# >>> adrmm zsh completion (generated by 'adrmm completions zsh') >>>
_adrmm() {
  local -a args out
  args=(${words[1,$CURRENT]})
  out=("${(@f)$(${ADRM_ADRM_BIN:-adrmm} __complete zsh "${args[@]}" 2>/dev/null)}")
  out=(${out:#__nofiles__})
  if (( ${#out} )); then
    _describe -t adrmm 'adrmm' out
    return 0
  fi
  return 0
}
compdef _adrmm adrmm
# <<< adrmm zsh completion <<<
`
}

// Fish returns the fish completion script for the given binary.
func Fish(cmd string) string {
	fn := "__" + cmd + "_fish_complete"
	// rm-compatible face: file completion stays enabled (no -f), so adrm
	// behaves like rm.
	return `# >>> ` + cmd + ` fish completion (generated by 'adrmm completions fish') >>>
function ` + fn + `
    set -l bin ` + cmd + `
    if set -q ADRM_ADRM_BIN
        set bin $ADRM_ADRM_BIN
    end
    set -l toks (commandline -opc) (commandline -ct)
    $bin __complete fish $toks 2>/dev/null
end
complete -c ` + cmd + ` -a '(` + fn + `)'
# <<< ` + cmd + ` fish completion <<<
`
}

// FileName returns the conventional file name for a shell's completion.
func FileName(shell, cmd string) string {
	switch shell {
	case "zsh":
		return "_" + cmd
	case "fish":
		return cmd + ".fish"
	default:
		return cmd + ".bash"
	}
}
